use std::fmt::Write;
use std::io;
use std::path::Path;

fn wolfram_argument_types() -> String {
    let mut schema =
        String::from("(* Generated by matheme-option-schema. *)\n\n$argumentTypes = <|\n");
    let actions = matheme::Action::wl_actions().filter(|(_, args)| !args.is_empty());
    for (index, (action, args)) in actions.enumerate() {
        if index > 0 {
            schema.push_str(",\n");
        }
        writeln!(schema, "  \"{action}\" -> <|").unwrap();
        let last = args.len() - 1;
        for (index, (key, pattern)) in args.into_iter().enumerate() {
            let separator = if index == last { "" } else { "," };
            writeln!(schema, "    \"{key}\" -> ({pattern}){separator}").unwrap();
        }
        schema.push_str("  |>");
    }
    schema.push_str("\n|>;\n");
    schema
}

fn main() -> io::Result<()> {
    let workspace = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    std::fs::write(
        workspace.join("Kernel/ArgumentTypes.wl"),
        wolfram_argument_types(),
    )
}
